-- ============================================================================
-- create_feed_sources.sql
--
-- Section 2 reference schema for a normalized feed catalog (`feed_sources`).
-- Idempotent — safe to run in the Supabase SQL Editor any number of times.
--
-- NOTE: the live ingestion pipeline currently reads from `rss_sources` (seeded
-- by sql/seed_all_feeds.sql). This table is the forward-looking, stricter schema
-- from the directive (CHECK constraints on ingest_method / native_lang). It is
-- created here so it exists; migrating ingestion onto it is a separate step.
-- ============================================================================

CREATE TABLE IF NOT EXISTS feed_sources (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name     text NOT NULL,
    region          text NOT NULL,
    feed_url        text UNIQUE NOT NULL,
    ingest_method   text NOT NULL CHECK (ingest_method IN ('rss', 'scrape')),
    translate_first boolean DEFAULT false NOT NULL,
    native_lang     text CHECK (native_lang IN ('ru', 'zh') OR native_lang IS NULL),
    active          boolean DEFAULT true NOT NULL,
    last_fetched_at timestamptz,
    created_at      timestamptz DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_feed_sources_active_method
    ON feed_sources (active, ingest_method);
CREATE INDEX IF NOT EXISTS idx_feed_sources_url
    ON feed_sources (feed_url);
