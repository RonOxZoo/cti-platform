-- ============================================================================
-- enable_pgvector.sql  —  vector store for RAG semantic retrieval (Pillar 3).
--
-- Apply in the Supabase SQL Editor. Idempotent.
--
-- Chunks of enriched intelligence are embedded (768-dim, Gemini
-- text-embedding-004) and stored here; `match_intel_chunks()` does the cosine
-- similarity search that rag/vector.py calls. Retrieval policy (enforced in
-- Python): chunk <=500 tokens / 10% overlap, similarity >= 0.82, top 3, deduped.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS intel_chunks (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      uuid REFERENCES intelligence_items(id) ON DELETE CASCADE,
    chunk_index  int  NOT NULL,
    content      text NOT NULL,
    content_hash text,
    embedding    vector(768),
    created_at   timestamptz DEFAULT timezone('utc', now()) NOT NULL,
    UNIQUE (item_id, chunk_index)
);

-- Approximate-nearest-neighbour index for cosine distance.
CREATE INDEX IF NOT EXISTS idx_intel_chunks_embedding
    ON intel_chunks USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);
CREATE INDEX IF NOT EXISTS idx_intel_chunks_item ON intel_chunks (item_id);

-- Cosine-similarity search. similarity = 1 - cosine_distance (<=> is cosine
-- distance under vector_cosine_ops). Returns the closest `match_count` chunks at
-- or above `match_threshold`.
CREATE OR REPLACE FUNCTION match_intel_chunks(
    query_embedding vector(768),
    match_threshold float,
    match_count int
)
RETURNS TABLE (
    id bigint,
    item_id uuid,
    chunk_index int,
    content text,
    similarity float
)
LANGUAGE sql STABLE
AS $$
    SELECT c.id, c.item_id, c.chunk_index, c.content,
           1 - (c.embedding <=> query_embedding) AS similarity
    FROM intel_chunks c
    WHERE c.embedding IS NOT NULL
      AND 1 - (c.embedding <=> query_embedding) >= match_threshold
    ORDER BY c.embedding <=> query_embedding
    LIMIT match_count;
$$;

